    public static String full(int i) {
        return BODY[i] + TAIL;
    }

    /** 反查：给定完整 prompt，判断是哪个预设，不是就返回 -1 */
    public static int match(String prompt) {
        if (prompt == null) return -1;
        for (int i = 0; i < BODY.length; i++) {
            if (prompt.startsWith(BODY[i])) return i;
        }
        return -1;
    }

